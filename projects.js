window.projectCover = function (project) {
  if (project.cover) return project.cover;
  return `assets/projects/${project.slug}/main.jpg`;
};

window.projectPictures = function (project, done) {
  if (project.images && project.images.length) {
    done(project.images.slice());
    return;
  }
  if (project._pictures) {
    done(project._pictures.slice());
    return;
  }
  if (project._pictureWait) {
    project._pictureWait.push(done);
    return;
  }
  project._pictureWait = [done];
  const files = ["main.jpg"];
  const root = location.pathname.includes("/projects/") ? "../" : "";
  const base = `${root}assets/projects/${project.slug}/`;
  const finish = () => {
    project._pictures = files.slice();
    const waiters = project._pictureWait || [];
    project._pictureWait = null;
    waiters.forEach((fn) => fn(files.slice()));
  };
  const step = (n) => {
    if (n > 40) {
      finish();
      return;
    }
    const img = new Image();
    img.onload = () => {
      files.push(`${n}.jpg`);
      step(n + 1);
    };
    img.onerror = finish;
    img.src = `${base}${n}.jpg`;
  };
  step(1);
};
